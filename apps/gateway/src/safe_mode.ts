/** Applies process-only overrides after the product env file has been loaded. */
export function applyGatewaySafeMode(env: NodeJS.ProcessEnv = process.env): boolean {
  if (env.BLUE_TANUKI_SAFE_MODE !== "1") return false;

  for (const key of SAFE_MODE_DISABLED_ENV_KEYS) env[key] = "";
  env.LLM_BACKEND = "stub";
  env.LLM_DEFAULT_BACKEND = "stub";
  env.COMPOSIO_DRY_RUN = "true";
  env.BLUE_TANUKI_DAILY_BRIEF_ENABLED = "0";
  env.BLUE_TANUKI_DAILY_BRIEF_GOOGLE_ENABLED = "0";
  return true;
}
